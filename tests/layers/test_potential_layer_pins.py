#: w -(e0)- z1 -(e1)- z2 -(e2)- z3 -(e3)- l, plus z1 -(e4)- z3: five power-law edges.
_FAST_NODES = ["w", "z1", "z2", "z3", "l"]
_FAST_EDGES = [("w", "z1", "pipe"), ("z1", "z2", "pipe"), ("z2", "z3", "pipe"),
               ("z3", "l", "pipe"), ("z1", "z3", "pipe")]


def _fast(*, linear_solver="auto", learnable=True, withdrawals=(), storage=(), name="e"):
    net = _net(_FAST_NODES, _FAST_EDGES)
    law = PowerLaw(_t([0.010, 0.008, 0.012, 0.009, 0.011]), 0.65, dp_transition=1e-6,
                   kind="pipe", learnable=learnable)
    layer = KirchhoffLayer(net, name, [law], boundary=["w", "l"], linear_solver=linear_solver,
                           withdrawals=withdrawals, storage=storage)
    assert not layer.mna
    return layer, law


def _fast_inputs(batch=None, grad=False):
    pb = _t([6.0, 0.5])
    src = _t([0.0, 0.02, -0.01, 0.015, 0.0])
    if batch:
        scale = torch.linspace(0.8, 1.2, batch, dtype=F64).reshape(batch, 1)
        pb, src = pb * scale, src * scale
    return pb.requires_grad_(grad), src.requires_grad_(grad)


def case_fast_primal():
    layer, _ = _fast()
    pb, src = _fast_inputs()
    return _solve(layer, (pb, {}, src), differentiable=False)



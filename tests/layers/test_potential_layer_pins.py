"""Bitwise pins of `KirchhoffLayer`'s two solve paths (core-unification M6, Task 25).

The layer solves a network by one of two assemblers: the fast path (every flow follows from the
potentials, so the Jacobian is the symmetric network matrix) and the general path (a law that
cannot give the flow from the potential difference gives a relation instead, and the solver
adds its flow as an unknown). Each case here runs one small, deterministic layer through
`solve` (and, where named, `flows`, `balance`, `residual`, `jacobian`, `adjoint`,
`linear_init`) and records the potentials `phi`, the flows `q`, the diagnostics
(`newton_iterations`, `linear_iterations`, `backend`, `converged`) and, where the case lists
parameters, the gradients of a fixed loss with respect to them. The reference is
`tests/golden/potential_layer.json`, generated by `benchmarks/regenerate_pins_golden.py`.

The comparison is the one of `tests/test_golden_orchestration.py` (exact under
`NOODL_GOLDEN_EXACT=1`, 1e-12 otherwise). Refactoring either assembler must leave the file
untouched; regenerate it only for a deliberate change of behaviour, with the controller's say.

Cases named `moves_*` pin what the merge of the two paths changes on purpose: a layer whose
only reason for the general path is a dynamic or context-reading law, with no implicit law.
"""


def _fast_step(scheme, withdrawal=False):
    storage = _fast_storage()
    ws = _emitters() if withdrawal else ()
    layer, law = _fast(storage=[storage], withdrawals=ws)
    pb, src = _fast_inputs()
    phi_prev = _t([6.0, 0.4, -0.2, 0.3, 0.5], grad=True)
    q_prev = torch.zeros(5, dtype=F64)
    kw: dict[str, Any] = {"dt": 0.3, "scheme": scheme, "history": (phi_prev, q_prev)}
    params: dict[str, torch.Tensor] = {"C": storage.C, "phi_prev": phi_prev, "law_C": law.C}
    if scheme == "trapezoidal":
        flow = _t([0.05, -0.02], grad=True)
        kw["storage_flow"] = flow
        params["storage_flow"] = flow
    diag: dict = {}
    phi, q = layer.solve(pb, {}, src, diagnostics=diag, **kw)
    w = layer.storage_flows(phi, {}, **kw)
    out = {"phi": ser(phi), "q": ser(q), "storage_flows": ser(w),
           "diagnostics": _diag_record(diag)}
    out["grads"] = ser(grads_of(_loss(phi, q) + (w * w).sum(), params))
    return out



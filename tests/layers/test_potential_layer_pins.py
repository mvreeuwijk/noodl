def _rc_storage_layer(learnable=True, withdrawal=False):
    """gnd <-V- s -R- a, a storage at a (and a second one at s and a when `withdrawal`)."""
    net = _net(["gnd", "s", "a"], [("s", "gnd", "voltage_source"), ("s", "a", "resistor")])
    storage = LinearStorage([2], _t([0.3]), initial=1.5, learnable=learnable)
    res = Resistance(_t([2.0]), learnable=learnable)
    ws = []
    storages = [storage]
    if withdrawal:
        ws = [_kirchhoff._Emitter(torch.tensor([1, 2]), torch.tensor([0.02, 0.03], dtype=F64))]
        storages = [storage, LinearStorage([1, 2], _t([0.05, 0.04]), learnable=learnable)]
    layer = KirchhoffLayer(net, "e", [PrescribedVoltage(_t([5.0])), res], boundary=["gnd"],
                           withdrawals=ws, storage=storages)
    return layer, storage, res, ws


